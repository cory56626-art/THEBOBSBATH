"""Upload the sound sheets as Roblox Audio assets and write src/ReplicatedStorage/SoundBank.luau.

    python3 tools/upload_audio.py [sheet ...]
Already-uploaded sheets are remembered in build/sounds/assets.json (only changed sheets are re-uploaded).
The API key is injected by the session proxy; nothing secret is stored here.
"""
import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOUNDS = os.path.join(ROOT, "build", "sounds")
CREATOR_USER_ID = "3167499144"
NAMES = {"creature": "Skinwalker creature sounds", "player": "Survivor sounds", "world": "Hospital ambience"}


def curl(*args):
    out = subprocess.run(["curl", "-sS", *args], capture_output=True, text=True, check=True).stdout
    return json.loads(out) if out.strip() else {}


def upload(sheet):
    path = os.path.join(SOUNDS, sheet + ".ogg")
    req = {"assetType": "Audio", "displayName": NAMES[sheet], "description": "The Walkers - " + NAMES[sheet],
           "creationContext": {"creator": {"userId": CREATOR_USER_ID}}}
    op = curl("-X", "POST", "https://apis.roblox.com/assets/v1/assets",
              "--form-string", "request=" + json.dumps(req), "--form", f"fileContent=@{path};type=audio/ogg")
    if "path" not in op:
        raise SystemExit(f"{sheet}: upload refused: {op}")
    for _ in range(60):
        time.sleep(2)
        st = curl(f"https://apis.roblox.com/assets/v1/{op['path']}")
        if st.get("done"):
            if "error" in st:
                raise SystemExit(f"{sheet}: {st['error']}")
            r = st["response"]
            print(f"{sheet}: asset {r['assetId']} moderation={r.get('moderationResult', {}).get('moderationState')}")
            return r["assetId"]
    raise SystemExit(f"{sheet}: upload still processing")


def main():
    assets_file = os.path.join(SOUNDS, "assets.json")
    assets = json.load(open(assets_file)) if os.path.exists(assets_file) else {}
    sheets = sys.argv[1:] or ["creature", "player", "world"]
    for sheet in sheets:
        digest = hashlib.sha1(open(os.path.join(SOUNDS, sheet + ".ogg"), "rb").read()).hexdigest()
        if assets.get(sheet, {}).get("sha1") == digest:
            print(f"{sheet}: unchanged, asset {assets[sheet]['id']}")
            continue
        assets[sheet] = {"id": upload(sheet), "sha1": digest}
        json.dump(assets, open(assets_file, "w"), indent=1)
    regions = json.load(open(os.path.join(SOUNDS, "regions.json")))
    lines = ["-- Generated by tools/upload_audio.py: sound sheets (asset ids) and the slice each sound occupies.",
             "return {"]
    for sheet, key in (("creature", "Creature"), ("player", "Player"), ("world", "World")):
        if sheet not in assets:
            continue
        lines.append(f"\t{key} = {{")
        lines.append(f'\t\tId = "rbxassetid://{assets[sheet]["id"]}",')
        lines.append("\t\tRegions = {")
        for name, (a, b) in regions[key].items():
            lines.append(f"\t\t\t{name} = {{ {a}, {b} }},")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    out = os.path.join(ROOT, "src", "ReplicatedStorage", "SoundBank.luau")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
