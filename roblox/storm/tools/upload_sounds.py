"""Upload build/sounds/storm.ogg as a Roblox Audio asset, let the game use it, and write
src/ReplicatedStorage/StormSoundBank.luau. Re-uploads only when the sheet changed.
The API key is injected by the session proxy; nothing secret is stored here.
"""
import hashlib
import json
import os
import subprocess
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOUNDS = os.path.join(ROOT, "build", "sounds")
CREATOR_USER_ID = "3167499144"
UNIVERSE = "4143610457"
STATE = os.path.join(HERE, "sound_assets.json")  # committed, so builds don't re-upload


def curl(*args):
    out = subprocess.run(["curl", "-sS", *args], capture_output=True, text=True, check=True).stdout
    return json.loads(out) if out.strip() else {}


def upload(path):
    req = {"assetType": "Audio", "displayName": "Steal a Storm sounds", "description": "Steal a Storm - game sounds",
           "creationContext": {"creator": {"userId": CREATOR_USER_ID}}}
    op = curl("-X", "POST", "https://apis.roblox.com/assets/v1/assets",
              "--form-string", "request=" + json.dumps(req), "--form", f"fileContent=@{path};type=audio/ogg")
    if "path" not in op:
        raise SystemExit(f"upload refused: {op}")
    for _ in range(60):
        time.sleep(2)
        st = curl(f"https://apis.roblox.com/assets/v1/{op['path']}")
        if st.get("done"):
            if "error" in st:
                raise SystemExit(str(st["error"]))
            r = st["response"]
            print(f"asset {r['assetId']} moderation={r.get('moderationResult', {}).get('moderationState')}")
            return r["assetId"]
    raise SystemExit("upload still processing")


def main():
    path = os.path.join(SOUNDS, "storm.ogg")
    digest = hashlib.sha1(open(path, "rb").read()).hexdigest()
    state = json.load(open(STATE)) if os.path.exists(STATE) else {}
    if state.get("sha1") != digest:
        state = {"id": upload(path), "sha1": digest}
        r = curl("-X", "PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                 "-H", "Content-Type: application/json", "--data-binary",
                 json.dumps({"subjectType": "Universe", "subjectId": UNIVERSE, "action": "Use",
                             "requests": [{"assetId": int(state["id"])}]}))
        print("permission:", r)
        json.dump(state, open(STATE, "w"), indent=1)
    else:
        print("unchanged, asset", state["id"])
    regions = json.load(open(os.path.join(SOUNDS, "regions.json")))["Storm"]
    lines = ["-- Generated by tools/upload_sounds.py: the sound sheet and where each sound sits in it (seconds).",
             "return {", f'\tId = "rbxassetid://{state["id"]}",', "\tRegions = {"]
    for name, (a, b) in regions.items():
        lines.append(f"\t\t{name} = {{ {a}, {b} }},")
    lines += ["\t},", "}"]
    out = os.path.join(ROOT, "src", "ReplicatedStorage", "StormSoundBank.luau")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
