"""Find every (Class, Property) the scripts set through new()/label()/button() or directly, and write a Luau check
that asks Roblox whether each property exists (catches typos that only show up on players' screens)."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
files = ["src/StarterPlayerScripts/P9Client.client.luau"]
pairs = set()


def table_keys(src, start):
    """Top-level keys of the Lua table literal starting at src[start] == '{'."""
    depth, i, keys, token_start = 0, start, [], start + 1
    while i < len(src):
        c = src[i]
        if c in "{(":
            depth += 1
        elif c in "})":
            depth -= 1
            if depth == 0:
                break
        elif c == "=" and depth == 1 and src[i + 1] != "=" and src[i - 1] not in "=<>~":
            m = re.search(r"(\w+)\s*$", src[token_start:i])
            if m:
                keys.append(m.group(1))
        elif c == "," and depth == 1:
            token_start = i + 1
        i += 1
    return keys


for f in files:
    src = open(os.path.join(ROOT, f)).read()
    for m in re.finditer(r'new\("(\w+)",\s*\{', src):
        for k in table_keys(src, m.end() - 1):
            pairs.add((m.group(1), k))
    for m in re.finditer(r'label\([\w.]+,\s*\{', src):
        for k in table_keys(src, m.end() - 1):
            pairs.add(("TextLabel", k))
direct = """
Sound PlaybackRegionsEnabled PlaybackRegion LoopRegion RollOffMinDistance RollOffMaxDistance Looped PlaybackSpeed
SpotLight Enabled|Motor6D Transform|Explosion BlastPressure BlastRadius DestroyJointRadiusPercent ExplosionType
Humanoid PlatformStand SeatPart DisplayDistanceType|VehicleSeat ThrottleFloat SteerFloat Occupant
LinearVelocity ForceLimitsEnabled ForceLimitMode VelocityConstraintMode RelativeTo VectorVelocity MaxAxesForce
AlignOrientation Mode MaxTorque Responsiveness CFrame|Smoke Color Size RiseVelocity Opacity
SurfaceGui Face SizingMode PixelsPerStud|Team TeamColor AutoAssignable|Part CustomPhysicalProperties Massless
BillboardGui StudsOffset MaxDistance AlwaysOnTop|TextButton AutoButtonColor TextScaled
"""
for group in direct.replace("\n", "|").split("|"):
    words = group.split()
    for k in words[1:]:
        pairs.add((words[0], k))
lines = ["-- generated by tools/check_props.py", "local bad, n = {}, 0"]
for cls, k in sorted(pairs):
    lines.append(f'do n += 1; local ok = pcall(function() local i = Instance.new("{cls}"); local _ = (i :: any).{k} end) '
                 f'if not ok then table.insert(bad, "{cls}.{k}") end end')
lines.append('return ("checked %d properties; missing: %s"):format(n, if #bad == 0 then "none" else table.concat(bad, ", "))')
open(os.path.join(HERE, "check_props.luau"), "w").write("\n".join(lines) + "\n")
print(len(pairs), "pairs")
