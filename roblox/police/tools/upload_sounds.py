"""Upload build/sounds/p9.ogg as a Roblox Audio asset, let the game use it, and write
src/ReplicatedStorage/P9SoundBank.luau. Re-uploads only when the sheet changed.
The API key is injected by the session proxy; nothing secret is stored here.
"""
import hashlib
import json
import os
import subprocess
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOUNDS = os.path.join(ROOT, "build", "sounds")
CREATOR_USER_ID = "3167499144"
UNIVERSE = "4143610457"
STATE = os.path.join(HERE, "sound_assets.json")  # committed, so builds don't re-upload


def curl(*args):
    out = subprocess.run(["curl", "-sS", *args], capture_output=True, text=True, check=True).stdout
    return json.loads(out) if out.strip() else {}


def upload(path):
    req = {"assetType": "Audio", "displayName": "Precinct 9 sounds", "description": "Precinct 9 - game sounds",
           "creationContext": {"creator": {"userId": CREATOR_USER_ID}}}
    op = curl("-X", "POST", "https://apis.roblox.com/assets/v1/assets",
              "--form-string", "request=" + json.dumps(req), "--form", f"fileContent=@{path};type=audio/ogg")
    if "path" not in op:
        raise SystemExit(f"upload refused: {op}")
    for _ in range(60):
        time.sleep(2)
        st = curl(f"https://apis.roblox.com/assets/v1/{op['path']}")
        if st.get("done"):
            if "error" in st:
                raise SystemExit(str(st["error"]))
            r = st["response"]
            print(f"asset {r['assetId']} moderation={r.get('moderationResult', {}).get('moderationState')}")
            return r["assetId"]
    raise SystemExit("upload still processing")


SHEETS = [("p9", "P9"), ("p9b", "P9b")]


def main():
    state = json.load(open(STATE)) if os.path.exists(STATE) else {}
    if "id" in state:  # older single-sheet format
        state = {"p9": state}
    regions = json.load(open(os.path.join(SOUNDS, "regions.json")))
    ids, lines_regions = [], []
    for i, (sheet, key) in enumerate(SHEETS):
        path = os.path.join(SOUNDS, sheet + ".ogg")
        digest = hashlib.sha1(open(path, "rb").read()).hexdigest()
        st = state.get(sheet, {})
        if st.get("sha1") != digest:
            st = {"id": upload(path), "sha1": digest}
            r = curl("-X", "PATCH", "https://apis.roblox.com/asset-permissions-api/v1/assets/permissions",
                     "-H", "Content-Type: application/json", "--data-binary",
                     json.dumps({"subjectType": "Universe", "subjectId": UNIVERSE, "action": "Use",
                                 "requests": [{"assetId": int(st["id"])}]}))
            print(sheet, "permission:", r)
            state[sheet] = st
            json.dump(state, open(STATE, "w"), indent=1)
        else:
            print(sheet, "unchanged, asset", st["id"])
        ids.append(f'"rbxassetid://{st["id"]}"')
        for name, (a, b) in regions[key].items():
            lines_regions.append(f"\t\t{name} = {{ {a}, {b}, {i + 1} }},")
    lines = ["-- Generated by tools/upload_sounds.py: the sound sheets and where each sound sits (start, end, sheet).",
             "return {", f"\tId = {ids[0]},", "\tIds = { " + ", ".join(ids) + " },", "\tRegions = {"]
    lines += lines_regions + ["\t},", "}"]
    out = os.path.join(ROOT, "src", "ReplicatedStorage", "P9SoundBank.luau")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
